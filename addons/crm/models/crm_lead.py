    partner_phone_update = fields.Boolean(string="Partner Phone will Update", readonly=True)
    is_partner_visible = fields.Boolean(string="Is Partner Visible", readonly=True)
    reveal_id = fields.Char(string="Reveal ID")
    iap_enrich_done = fields.Boolean(string="Enrichment done", help="Whether IAP service for lead enrichment based on email has been performed on this lead.")
    show_enrich_button = fields.Boolean(string="Allow manual enrich", readonly=True)
