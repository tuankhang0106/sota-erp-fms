    kanban_state = fields.Selection(selection=[["grey","No next activity planned"],["red","Next activity late"],["green","Next activity is planned"]], string="Kanban State", readonly=True)
    tag_ids = fields.Many2many(comodel_name="crm.tag", string="Tags", help="Classify and analyze your lead/opportunity categories like: Training, Service")
    color = fields.Integer(string="Color Index")
    expected_revenue = fields.Monetary(string="Expected Revenue")
    prorated_revenue = fields.Monetary(string="Prorated Revenue", readonly=True)
    recurring_revenue = fields.Monetary(string="Recurring Revenues")
    recurring_plan = fields.Many2one(comodel_name="crm.recurring.plan", string="Recurring Plan")
    recurring_revenue_monthly = fields.Monetary(string="Expected MRR", readonly=True)
    recurring_revenue_monthly_prorated = fields.Monetary(string="Prorated MRR", readonly=True)
    company_currency = fields.Many2one(comodel_name="res.currency", string="Currency", readonly=True)
    date_closed = fields.Datetime(string="Closed Date", readonly=True)
    date_action_last = fields.Datetime(string="Last Action", readonly=True)
