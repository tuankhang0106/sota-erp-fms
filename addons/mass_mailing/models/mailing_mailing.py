# -*- coding: utf-8 -*-
from odoo import models, fields, api

class MailingMailing(models.Model):
    _name = 'mailing.mailing'
    _description = 'MAILING MAILING'
    _order = 'id desc'

    name = fields.Char(string="Name")
    source_id = fields.Many2one(comodel_name="utm.source", string="Source", required=True)
    lang = fields.Char(string="Language", help="Optional translation language (ISO code) to select when sending out an email. If not set, the english version will be used. This should usually be a placeholder expression that provides the appropriate language, e.g. {{ object.partner_id.lang }}.")
    render_model = fields.Char(string="Rendering Model", readonly=True)
    activity_ids = fields.One2many(comodel_name="mail.activity", inverse_name='parent_id', string="Activities")
    activity_state = fields.Selection(selection=[["overdue","Overdue"],["today","Today"],["planned","Planned"]], string="Activity State", readonly=True, help="Status based on activities\nOverdue: Due date is already passed\nToday: Activity date is today\nPlanned: Future activities.")
    activity_user_id = fields.Many2one(comodel_name="res.users", string="Responsible User")
    activity_type_id = fields.Many2one(comodel_name="mail.activity.type", string="Next Activity Type")
    activity_type_icon = fields.Char(string="Activity Type Icon", readonly=True, help="Font awesome icon e.g. fa-tasks")
    activity_date_deadline = fields.Date(string="Next Activity Deadline", readonly=True)
    my_activity_date_deadline = fields.Date(string="My Activity Deadline", readonly=True)
    activity_summary = fields.Char(string="Next Activity Summary")
    activity_exception_decoration = fields.Selection(selection=[["warning","Alert"],["danger","Error"]], string="Activity Exception Decoration", readonly=True, help="Type of the exception activity on record.")
    activity_exception_icon = fields.Char(string="Icon", readonly=True, help="Icon to indicate an exception activity.")
    activity_calendar_event_id = fields.Many2one(comodel_name="calendar.event", string="Next Activity Calendar Event", readonly=True)
    message_is_follower = fields.Boolean(string="Is Follower", readonly=True)
    message_follower_ids = fields.One2many(comodel_name="mail.followers", inverse_name='parent_id', string="Followers")
    message_partner_ids = fields.Many2many(comodel_name="res.partner", string="Followers (Partners)")
    message_ids = fields.One2many(comodel_name="mail.message", inverse_name='parent_id', string="Messages")
    has_message = fields.Boolean(string="Has Message", readonly=True)
    message_needaction = fields.Boolean(string="Action Needed", readonly=True, help="If checked, new messages require your attention.")
    message_needaction_counter = fields.Integer(string="Number of Actions", readonly=True, help="Number of messages requiring action")
    message_has_error = fields.Boolean(string="Message Delivery error", readonly=True, help="If checked, some messages have a delivery error.")
    message_has_error_counter = fields.Integer(string="Number of errors", readonly=True, help="Number of messages with delivery error")
    message_attachment_count = fields.Integer(string="Attachment Count", readonly=True)
    message_main_attachment_id = fields.Many2one(comodel_name="ir.attachment", string="Main Attachment")
    website_message_ids = fields.One2many(comodel_name="mail.message", inverse_name='parent_id', string="Website Messages", help="Website communication history")
    message_has_sms_error = fields.Boolean(string="SMS Delivery error", readonly=True, help="If checked, some messages have a delivery error.")
    active = fields.Boolean(string="Active")
    subject = fields.Char(string="Subject", required=True)
    preview = fields.Char(string="Preview", help="Catchy preview sentence that encourages recipients to open this email.\nIn most inboxes, this is displayed next to the subject.\nKeep it empty if you prefer the first characters of your email content to appear instead.")
    email_from = fields.Char(string="Send From", required=True)
    favorite = fields.Boolean(string="Favorite")
    favorite_date = fields.Datetime(string="Favorite Date", readonly=True, help="When this mailing was added in the favorites")
    sent_date = fields.Datetime(string="Sent Date")
    schedule_type = fields.Selection(selection=[["now","Send now"],["scheduled","Send on"]], string="Schedule", required=True, readonly=True)
    schedule_date = fields.Datetime(string="Scheduled for", readonly=True)
    calendar_date = fields.Datetime(string="Calendar Date", readonly=True, help="Date at which the mailing was or will be sent.")
    body_arch = fields.Html(string="Body")
    body_html = fields.Html(string="Body converted to be sent by mail")
    is_body_empty = fields.Boolean(string="Is Body Empty", readonly=True)
    attachment_ids = fields.Many2many(comodel_name="ir.attachment", string="Attachments")
    keep_archives = fields.Boolean(string="Keep Archives")
    campaign_id = fields.Many2one(comodel_name="utm.campaign", string="UTM Campaign")
    medium_id = fields.Many2one(comodel_name="utm.medium", string="Medium", help="UTM Medium: delivery method (email, sms, ...)")
    state = fields.Selection(selection=[["draft","Draft"],["in_queue","In Queue"],["sending","Sending"],["done","Sent"]], string="Status", required=True)
    color = fields.Integer(string="Color Index")
    user_id = fields.Many2one(comodel_name="res.users", string="Responsible")
    mailing_type = fields.Selection(selection=[["mail","Email"]], string="Mailing Type", required=True)
    mailing_type_description = fields.Char(string="Mailing Type Description", readonly=True)
    reply_to_mode = fields.Selection(selection=[["update","Recipient Followers"],["new","Specified Email Address"]], string="Reply-To Mode", help="Thread: replies go to target document. Email: replies are routed to a given email.")
    reply_to = fields.Char(string="Reply To", help="Preferred Reply-To Address")
    mailing_model_real = fields.Char(string="Recipients Real Model", readonly=True)
    mailing_model_id = fields.Many2one(comodel_name="ir.model", string="Recipients Model", required=True)
    mailing_model_name = fields.Char(string="Recipients Model Name", readonly=True)
    mailing_domain = fields.Char(string="Domain")
    mail_server_available = fields.Boolean(string="Mail Server Available", readonly=True, help="Technical field used to know if the user has activated the outgoing mail server option in the settings")
    mail_server_id = fields.Many2one(comodel_name="ir.mail_server", string="Mail Server", help="Use a specific mail server in priority. Otherwise Odoo relies on the first outgoing mail server available (based on their sequencing) as it does for normal mails.")
    contact_list_ids = fields.Many2many(comodel_name="mailing.list", string="Mailing Lists")
    mailing_filter_id = fields.Many2one(comodel_name="mailing.filter", string="Favorite Filter")
    mailing_filter_domain = fields.Char(string="Favorite filter domain", readonly=True)
    mailing_filter_count = fields.Integer(string="# Favorite Filters", readonly=True)
    ab_testing_completed = fields.Boolean(string="A/B Testing Campaign Finished", readonly=True)
    ab_testing_description = fields.Html(string="A/B Testing Description", readonly=True)
    ab_testing_enabled = fields.Boolean(string="Allow A/B Testing", help="If checked, recipients will be mailed only once for the whole campaign. This lets you send different mailings to randomly selected recipients and test the effectiveness of the mailings, without causing duplicate messages.")
    ab_testing_mailings_count = fields.Integer(string="A/B Test Mailings #", readonly=True)
    ab_testing_pc = fields.Integer(string="A/B Testing percentage", help="Percentage of the contacts that will be mailed. Recipients will be chosen randomly.")
    ab_testing_schedule_datetime = fields.Datetime(string="Send Final On", help="Date that will be used to know when to determine and send the winner mailing")
    ab_testing_winner_selection = fields.Selection(selection=[["manual","Manual"],["opened_ratio","Highest Open Rate"],["clicks_ratio","Highest Click Rate"],["replied_ratio","Highest Reply Rate"],["crm_lead_count","Leads"]], string="Winner Selection", help="Selection to determine the winner mailing that will be sent.")
    kpi_mail_required = fields.Boolean(string="KPI mail required")
    mailing_trace_ids = fields.One2many(comodel_name="mailing.trace", inverse_name='parent_id', string="Emails Statistics")
    total = fields.Integer(string="Total", readonly=True)
    scheduled = fields.Integer(string="Scheduled", readonly=True)
    expected = fields.Integer(string="Expected", readonly=True)
    canceled = fields.Integer(string="Canceled", readonly=True)
    sent = fields.Integer(string="Sent", readonly=True)
    delivered = fields.Integer(string="Delivered", readonly=True)
    opened = fields.Integer(string="Opened", readonly=True)
    clicked = fields.Integer(string="Clicked", readonly=True)
    replied = fields.Integer(string="Replied", readonly=True)
    bounced = fields.Integer(string="Bounced", readonly=True)
    failed = fields.Integer(string="Failed", readonly=True)
    received_ratio = fields.Integer(string="Received Ratio", readonly=True)
    opened_ratio = fields.Integer(string="Opened Ratio", readonly=True)
    replied_ratio = fields.Integer(string="Replied Ratio", readonly=True)
    bounced_ratio = fields.Integer(string="Bounced Ratio", readonly=True)
    clicks_ratio = fields.Integer(string="Number of Clicks", readonly=True)
    next_departure = fields.Datetime(string="Scheduled date", readonly=True)
    warning_message = fields.Char(string="Warning Message", readonly=True, help="Warning message displayed in the mailing form view")
    use_leads = fields.Boolean(string="Use Leads", readonly=True)
    crm_lead_count = fields.Integer(string="Leads/Opportunities Count", readonly=True)
