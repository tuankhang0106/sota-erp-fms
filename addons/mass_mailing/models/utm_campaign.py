# -*- coding: utf-8 -*-
from odoo import models, fields, api

class UtmCampaign(models.Model):
    _name = 'utm.campaign'
    _description = 'UTM CAMPAIGN'
    _order = 'id desc'

    name = fields.Char(string="Campaign Identifier", required=True)
    title = fields.Char(string="Campaign Name", required=True)
    user_id = fields.Many2one(comodel_name="res.users", string="Responsible", required=True)
    stage_id = fields.Many2one(comodel_name="utm.stage", string="Stage", required=True)
    tag_ids = fields.Many2many(comodel_name="utm.tag", string="Tags")
    is_auto_campaign = fields.Boolean(string="Automatically Generated Campaign", help="Allows us to filter relevant Campaigns")
    color = fields.Integer(string="Color Index")
    click_count = fields.Integer(string="Number of clicks generated by the campaign", readonly=True)
    use_leads = fields.Boolean(string="Use Leads", readonly=True)
    crm_lead_count = fields.Integer(string="Leads/Opportunities count", readonly=True)
    mailing_mail_ids = fields.One2many(comodel_name="mailing.mailing", inverse_name='parent_id', string="Mass Mailings")
    mailing_mail_count = fields.Integer(string="Number of Mass Mailing", readonly=True)
    is_mailing_campaign_activated = fields.Boolean(string="Is Mailing Campaign Activated", readonly=True)
    ab_testing_mailings_count = fields.Integer(string="A/B Test Mailings #", readonly=True)
    ab_testing_completed = fields.Boolean(string="A/B Testing Campaign Finished")
    ab_testing_schedule_datetime = fields.Datetime(string="Send Final On", help="Date that will be used to know when to determine and send the winner mailing")
    ab_testing_total_pc = fields.Integer(string="Total A/B test percentage", readonly=True)
    ab_testing_winner_selection = fields.Selection(selection=[["manual","Manual"],["opened_ratio","Highest Open Rate"],["clicks_ratio","Highest Click Rate"],["replied_ratio","Highest Reply Rate"],["crm_lead_count","Leads"]], string="Winner Selection", help="Selection to determine the winner mailing that will be sent.")
    received_ratio = fields.Integer(string="Received Ratio", readonly=True)
    opened_ratio = fields.Integer(string="Opened Ratio", readonly=True)
    replied_ratio = fields.Integer(string="Replied Ratio", readonly=True)
    bounced_ratio = fields.Integer(string="Bounced Ratio", readonly=True)
