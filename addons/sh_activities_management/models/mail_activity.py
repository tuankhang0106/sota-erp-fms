# -*- coding: utf-8 -*-
from odoo import models, fields, api

class MailActivityInherit(models.Model):
    _inherit = 'mail.activity'

    res_model_id = fields.Many2one(comodel_name="ir.model", string="Document Model", required=True)
    res_model = fields.Char(string="Related Document Model", readonly=True)
    res_id = fields.Char(string="Related Document ID")
    res_name = fields.Char(string="Document Name", readonly=True)
    activity_type_id = fields.Many2one(comodel_name="mail.activity.type", string="Activity Type")
    activity_category = fields.Selection(selection=[["default","None"],["upload_file","Upload Document"],["phonecall","Phonecall"],["meeting","Meeting"]], string="Action", readonly=True, help="Actions may trigger specific behavior like opening calendar view or automatically mark as done when a document is uploaded")
    activity_decoration = fields.Selection(selection=[["warning","Alert"],["danger","Error"]], string="Decoration Type", readonly=True, help="Change the background color of the related activities of this type.")
    icon = fields.Char(string="Icon", readonly=True, help="Font awesome icon e.g. fa-tasks")
    summary = fields.Char(string="Summary")
    note = fields.Html(string="Note")
    date_deadline = fields.Date(string="Due Date", required=True)
    automated = fields.Boolean(string="Automated activity", readonly=True, help="Indicates this activity has been created automatically and not by any user.")
    user_id = fields.Many2one(comodel_name="res.users", string="Assigned to", required=True)
    request_partner_id = fields.Many2one(comodel_name="res.partner", string="Requesting Partner")
    state = fields.Selection(selection=[["overdue","Overdue"],["today","Today"],["planned","Planned"],["done","Done"],["cancel","Cancelled"]], string="State", readonly=True)
    recommended_activity_type_id = fields.Many2one(comodel_name="mail.activity.type", string="Recommended Activity Type")
    previous_activity_type_id = fields.Many2one(comodel_name="mail.activity.type", string="Previous Activity Type", readonly=True)
    has_recommended_activities = fields.Boolean(string="Next activities available", readonly=True)
    mail_template_ids = fields.Many2many(comodel_name="mail.template", string="Email templates", readonly=True)
    chaining_type = fields.Selection(selection=[["suggest","Suggest Next Activity"],["trigger","Trigger Next Activity"]], string="Chaining Type", readonly=True)
    can_write = fields.Boolean(string="Can Write", readonly=True)
    calendar_event_id = fields.Many2one(comodel_name="calendar.event", string="Calendar Meeting")
    mobile_push_sent = fields.Boolean(string="Mobile Push Sent")
    mobile_push_sent_at = fields.Datetime(string="Mobile Push Sent At")
    mobile_push_reminder_sent_keys = fields.Text(string="Mobile Push Reminder Sent Keys")
    mobile_push_error = fields.Text(string="Mobile Push Error")
    domain_sale_team_ids = fields.Many2many(comodel_name="crm.team", string="Sales Teams", readonly=True)
    sale_team_id = fields.Many2one(comodel_name="crm.team", string="Sale Team")
    crm_department_id = fields.Many2one(comodel_name="crm.department", string="Crm Department")
    active = fields.Boolean(string="Active")
    supervisor_ids = fields.Many2many(comodel_name="res.users", string="Supervisors")
    department_ids = fields.Many2many(comodel_name="hr.department", string="Department")
    sh_activity_tags = fields.Many2many(comodel_name="sh.activity.tags", string="Activity Tags")
    sh_state = fields.Selection(selection=[["overdue","Overdue"],["today","Today"],["planned","Planned"],["done","Done"],["cancel","Cancelled"]], string="Sh State")
    date_done = fields.Date(string="Completed Date", readonly=True)
    feedback = fields.Text(string="Feedback")
    text_note = fields.Char(string="Notes In Char format ", readonly=True)
    sh_user_ids = fields.Many2many(comodel_name="res.users", string="Assign Multi Users")
    sh_display_multi_user = fields.Boolean(string="Sh Display Multi User", readonly=True)
    company_id = fields.Many2one(comodel_name="res.company", string="Company")
    color = fields.Integer(string="Color Index")
    sh_create_individual_activity = fields.Boolean(string="Individual activities for multi users ?")
    sh_activity_alarm_ids = fields.Many2many(comodel_name="sh.activity.alarm", string="Reminders")
    sh_date_deadline = fields.Datetime(string="Reminder Due Date", required=True)
    due_in_text = fields.Char(string="Due In", readonly=True)
    activity_cancel = fields.Boolean(string="Activity Cancel")
    activity_done = fields.Boolean(string="Activity Done")
    sh_activity_id = fields.Many2one(comodel_name="sh.recurring.activities", string="Sh Activity")
    reference = fields.Char(string="Related Document")
    crm_sr_revenue = fields.Char(string="Order Revenue")
    crm_sr_profit = fields.Char(string="Order Gross Profit")
    crm_sr_currency_id = fields.Many2one(comodel_name="res.currency", string="Crm Sr Currency", readonly=True)
    crm_sr_show_amount = fields.Boolean(string="Crm Sr Show Amount", readonly=True)
