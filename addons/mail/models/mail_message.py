# -*- coding: utf-8 -*-
from odoo import models, fields, api

class MailMessage(models.Model):
    _name = 'mail.message'
    _description = 'MAIL MESSAGE'
    _order = 'id desc'

    subject = fields.Char(string='Subject')
    date = fields.Datetime(string='Date')
    body = fields.Html(string='Contents')
    description = fields.Char(string='Short description', readonly=True, help='Message description: either the subject, or the beginning of the body')
    preview = fields.Char(string='Preview', readonly=True, help='The text-only beginning of the body used as email preview.')
    attachment_ids = fields.Many2many(comodel_name='ir.attachment', string='Attachments')
    parent_id = fields.Many2one(comodel_name='mail.message', string='Parent Message')
    child_ids = fields.One2many(comodel_name='mail.message', inverse_name='channel_id', string='Child Messages')
    model = fields.Char(string='Related Document Model')
    res_id = fields.Char(string='Related Document ID')
    record_name = fields.Char(string='Message Record Name')
    link_preview_ids = fields.One2many(comodel_name='mail.link.preview', inverse_name='channel_id', string='Link Previews')
    message_type = fields.Selection(selection=[["email","Email"],["comment","Comment"],["notification","System notification"],["auto_comment","Automated Targeted Notification"],["user_notification","User Specific Notification"],["sms","SMS"],["snailmail","Snailmail"]], string='Type', required=True, help='Message type: email for email message, notification for system message, comment for other messages such as user replies')
    subtype_id = fields.Many2one(comodel_name='mail.message.subtype', string='Subtype')
    mail_activity_type_id = fields.Many2one(comodel_name='mail.activity.type', string='Mail Activity Type')
    is_internal = fields.Boolean(string='Employee Only', help='Hide to public / portal users, independently from subtype configuration.')
    email_from = fields.Char(string='From', help='Email address of the sender. This field is set when no matching partner is found and replaces the author_id field in the chatter.')
    author_id = fields.Many2one(comodel_name='res.partner', string='Author', help='Author of the message. If not set, email_from may hold an email address that did not match any partner.')
    author_avatar = fields.Binary(string='Author\'s avatar')
    author_guest_id = fields.Many2one(comodel_name='mail.guest', string='Guest')
    is_current_user_or_guest_author = fields.Boolean(string='Is Current User Or Guest Author', readonly=True)
    partner_ids = fields.Many2many(comodel_name='res.partner', string='Recipients')
    notified_partner_ids = fields.Many2many(comodel_name='res.partner', string='Partners with Need Action')
    needaction = fields.Boolean(string='Need Action', readonly=True)
    has_error = fields.Boolean(string='Has error', readonly=True)
    notification_ids = fields.One2many(comodel_name='mail.notification', inverse_name='channel_id', string='Notifications')
    starred_partner_ids = fields.Many2many(comodel_name='res.partner', string='Favorited By')
    starred = fields.Boolean(string='Starred', readonly=True, help='Current user has a starred notification linked to this message')
    tracking_value_ids = fields.One2many(comodel_name='mail.tracking.value', inverse_name='channel_id', string='Tracking values', help='Tracked values are stored in a separate model. This field allow to reconstruct the tracking and to generate statistics on the model.')
    reply_to_force_new = fields.Boolean(string='No threading for answers', help='If true, answers do not go in the original document discussion thread. Instead, it will check for the reply_to in tracking message-id and redirected accordingly. This has an impact on the generated message-id.')
    message_id = fields.Char(string='Message-Id', readonly=True, help='Message unique identifier')
    reply_to = fields.Char(string='Reply-To', help='Reply email address. Setting the reply_to bypasses the automatic thread creation.')
    mail_server_id = fields.Many2one(comodel_name='ir.mail_server', string='Outgoing mail server')
    email_layout_xmlid = fields.Char(string='Layout')
    email_add_signature = fields.Boolean(string='Email Add Signature')
    mail_ids = fields.One2many(comodel_name='mail.mail', inverse_name='channel_id', string='Mails')
    canned_response_ids = fields.One2many(comodel_name='mail.shortcode', inverse_name='channel_id', string='Canned Responses')
    reaction_ids = fields.One2many(comodel_name='mail.message.reaction', inverse_name='channel_id', string='Reactions')
    has_sms_error = fields.Boolean(string='Has SMS error', readonly=True)
    snailmail_error = fields.Boolean(string='Snailmail message in error', readonly=True)
    letter_ids = fields.One2many(comodel_name='snailmail.letter', inverse_name='channel_id', string='Letter')
